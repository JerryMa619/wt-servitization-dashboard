 assert.equal(await action('maintenance-support'),'Enhanced Monitoring');assert.equal(await action('availability-assurance'),'Planned Maintenance');
 assert.ok((await comparison().getByRole('article',{name:'Availability assurance'}).innerText()).includes('-3 slots'));
 await comparison().getByRole('button',{name:/^(Apply|Applied:) Availability assurance$/}).click();
 assert.equal(await page.getByTestId('recommendation').innerText(),'Planned Maintenance');
 const waiting=page.waitForEvent('download');await comparison().getByRole('button',{name:'Export contract comparison'}).click();
 const dl=await waiting;const doc=JSON.parse(readFileSync(await dl.path(),'utf8'));
 assert.equal(doc.cycle,171);assert.equal(doc.comparisons.length,2);assert.equal(doc.realizedKPI,'not measured');
 assert.equal(doc.prediction.unit,'cycles');assert.ok(!JSON.stringify(doc).includes('finalRUL'));
