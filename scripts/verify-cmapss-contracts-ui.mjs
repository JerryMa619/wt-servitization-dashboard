 const active=JSON.parse(readFileSync(await(await exp).path(),'utf8'));
 assert.equal(active.contract.terms.id,'availability-assurance');
 await capture('intervention-comparison-desktop');
 await comparison().getByRole('button',{name:'Query and validate the applied contract'}).click();
 await work().getByRole('combobox',{name:'Semantic query'}).selectOption('contract');
 await work().getByRole('button',{name:'Run RDF / SHACL / SPARQL'}).click();
